//! Native systemd service registration. No shell or long-running wrapper.
use crate::{
    cli::CommonOpts,
    native::{self, Result, Scope},
};
use std::{
    fs,
    path::{Path, PathBuf},
    process::Command,
};

fn no_control_chars(value: &str) -> Result<()> {
    if value.chars().any(char::is_control) {
        return Err("Control characters are not supported in systemd unit values".into());
    }
    Ok(())
}

// systemd uses its own quoting grammar, not shell quoting.
// Percent specifiers expand even inside quotes.
fn quote(value: &str) -> Result<String> {
    no_control_chars(value)?;
    Ok(format!(
        "\"{}\"",
        value.replace('\\', "\\\\").replace('"', "\\\"").replace('%', "%%")
    ))
}

fn render_unit(
    name: &str,
    cwd: Option<&str>,
    dependencies: &[String],
    opts: &CommonOpts,
    scope: Scope<'_>,
) -> Result<String> {
    if !native::valid_name(name) || name.ends_with(".service") {
        return Err("Service name must start with an ASCII letter or digit and contain only letters, digits, '.', '_' or '-' (no .service suffix, maximum 100 bytes)".into());
    }
    if !dependencies.is_empty()
        || opts.pass.is_some()
        || !opts.restart_if.is_empty()
        || !opts.restart_if_not.is_empty()
        || opts.pass_start_args
        || !opts.path.is_empty()
        || !opts.path_prepend.is_empty()
        || opts.priority.is_some()
        || opts.interactive
        || opts.log_dir.is_some()
        || opts.log_as.is_some()
        || opts.log_cmd_as.is_some()
        || opts.log_rotate.is_some()
        || opts.log_retain.is_some()
    {
        return Err("This option is not supported by the initial systemd backend; see docs/platforms.md".into());
    }

    let program = opts.command.first().ok_or("Missing executable")?;
    native::check_executable(program)?;

    let args = opts.command.iter().map(|arg| quote(arg)).collect::<Result<Vec<_>>>()?;
    let restart = if opts.restart {
        "always"
    } else if opts.no_restart {
        "no"
    } else {
        "on-failure"
    };
    let timeout = opts.stop_timeout.unwrap_or(3000);
    if timeout == 0 {
        return Err("--stop-timeout must be positive on Linux (systemd interprets zero as infinity)".into());
    }
    // ':' disables systemd's variable substitution in ExecStart; no shell is used.
    let mut unit = format!(
        "# Generated by Shawl\n[Unit]\nDescription=Shawl service {name}\n\n[Service]\nType=exec\nExecStart=:{}\nRestart={restart}\nTimeoutStopSec={timeout}ms\nKillSignal=SIGINT\nKillMode=control-group\n",
        args.join(" ")
    );
    if let Scope::System(user) = scope {
        unit.push_str(&format!("User={user}\n"));
    }
    if let Some(delay) = opts.restart_delay {
        unit.push_str(&format!("RestartSec={delay}ms\n"));
    }
    if let Some(cwd) = cwd {
        no_control_chars(cwd)?;
        // WorkingDirectory is a path value, not a word list; do not shell-quote it.
        if !Path::new(cwd).is_absolute()
            || !Path::new(cwd).is_dir()
            || cwd.ends_with(char::is_whitespace)
            || cwd.contains('\\')
        {
            return Err(
                "Working directory must be an existing absolute directory without backslashes or trailing whitespace"
                    .into(),
            );
        }
        unit.push_str(&format!("WorkingDirectory={}\n", cwd.replace('%', "%%")));
    }
    for (key, value) in &opts.env {
        if !native::valid_env_key(key) {
            return Err("Invalid environment variable name".into());
        }
        unit.push_str(&format!("Environment={}\n", quote(&format!("{key}={value}"))?));
    }
    if opts.no_log || opts.no_log_cmd {
        unit.push_str("StandardOutput=null\nStandardError=null\n");
    } else {
        unit.push_str("StandardOutput=journal\nStandardError=journal\n");
    }
    unit.push_str(match scope {
        Scope::User => "\n[Install]\nWantedBy=default.target\n",
        Scope::System(_) => "\n[Install]\nWantedBy=multi-user.target\n",
    });
    Ok(unit)
}

fn unit_dir(scope: Scope<'_>) -> Result<PathBuf> {
    if matches!(scope, Scope::System(_)) {
        return Ok(PathBuf::from("/etc/systemd/system"));
    }
    let base = match std::env::var_os("XDG_CONFIG_HOME").filter(|x| !x.is_empty()) {
        Some(path) => PathBuf::from(path),
        None => PathBuf::from(std::env::var_os("HOME").ok_or("HOME is not set")?).join(".config"),
    };
    if !base.is_absolute() {
        return Err("The user configuration directory must be absolute".into());
    }
    Ok(base.join("systemd/user"))
}

fn systemctl(scope: Scope<'_>) -> Command {
    // Use a system-installed binary, particularly when invoked as root.
    let mut command = Command::new(if Path::new("/usr/bin/systemctl").is_file() {
        "/usr/bin/systemctl"
    } else {
        "/bin/systemctl"
    });
    if matches!(scope, Scope::System(_)) {
        // Do not allow inherited bus or unit-path overrides for privileged registration.
        command.env_clear();
    }
    command.arg(match scope {
        Scope::User => "--user",
        Scope::System(_) => "--system",
    });
    command
}

fn reload(scope: Scope<'_>) -> Result<()> {
    let status = systemctl(scope).arg("daemon-reload").status()?;
    if !status.success() {
        return Err(format!("systemctl daemon-reload failed: {status}").into());
    }
    Ok(())
}

pub fn add_service(name: &str, cwd: Option<&str>, dependencies: &[String], opts: &CommonOpts) -> Result<()> {
    let scope = native::scope(opts)?;
    let unit = render_unit(name, cwd, dependencies, opts, scope)?;
    let filename = format!("{name}.service");
    // Check the manager as well as the target file; never overwrite an existing service.
    let existing = systemctl(scope)
        .args(["show", "--property=LoadState", "--value", "--", &filename])
        .output()?;
    if String::from_utf8_lossy(&existing.stdout).trim() != "not-found" {
        return Err("Service already exists or systemd manager is unavailable".into());
    }

    let dir = unit_dir(scope)?;
    fs::create_dir_all(&dir)?;
    let path = dir.join(&filename);
    native::write_new(&path, &unit)?;
    if let Err(error) = reload(scope) {
        fs::remove_file(&path).map_err(|cleanup| format!("Reload failed ({error}); cleanup failed ({cleanup})"))?;
        reload(scope)
            .map_err(|cleanup| format!("Reload failed ({error}); unit removed but reload failed ({cleanup})"))?;
        return Err(error);
    }
    // The invoking shell and the user manager can have different XDG paths.
    // Confirm the manager really loaded our file instead of reporting success
    // for a missing or shadowed unit.
    let verification = (|| -> Result<()> {
        let output = systemctl(scope)
            .args(["show", "--property=LoadState,FragmentPath,Type,User", "--", &filename])
            .output()?;
        if !output.status.success() {
            return Err("Unable to inspect registered unit".into());
        }
        let stdout = String::from_utf8(output.stdout)?;
        let loaded = stdout.lines().any(|line| line == "LoadState=loaded");
        let fragment = stdout.lines().find_map(|line| line.strip_prefix("FragmentPath="));
        let expected = fs::canonicalize(&path)?;
        if !loaded || fragment.and_then(|p| fs::canonicalize(p).ok()).as_ref() != Some(&expected) {
            return Err(
                "The systemd manager did not load the generated unit; check its configuration directory".into(),
            );
        }
        if !stdout.lines().any(|line| line == "Type=exec") {
            return Err(
                "The service requires Type=exec (systemd 240 or newer); check the manager version and native overrides"
                    .into(),
            );
        }
        if let Scope::System(user) = scope {
            let effective_user = stdout.lines().find_map(|line| line.strip_prefix("User="));
            if effective_user != Some(user) {
                return Err(
                    "The effective systemd User differs from the requested account; check native overrides".into(),
                );
            }
        }
        Ok(())
    })();
    if let Err(error) = verification {
        fs::remove_file(&path)
            .map_err(|cleanup| format!("Verification failed ({error}); cleanup failed ({cleanup})"))?;
        reload(scope)
            .map_err(|cleanup| format!("Verification failed ({error}); unit removed but reload failed ({cleanup})"))?;
        return Err(error);
    }
    let flag = match scope {
        Scope::User => "--user",
        Scope::System(_) => "--system",
    };
    println!("Registered {filename}. Start it with systemctl {flag} start {filename}.");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn opts() -> CommonOpts {
        CommonOpts {
            command: vec!["/bin/sh".into(), "-c".into(), "printf '%s' \"$HOME\"".into()],
            ..Default::default()
        }
    }

    #[test]
    fn rejects_unsafe_names() {
        for name in ["", "../test", "a/b", "-bad", "bad\n[Service]", "test.service"] {
            assert!(render_unit(name, None, &[], &opts(), Scope::User).is_err());
        }
    }

    #[test]
    fn quotes_args_without_shell_or_variable_expansion() {
        let mut options = opts();
        options.command.extend(["".into(), "a b".into(), "a\\b".into()]);
        options.env.push(("TEST".into(), "hello $HOME 100%".into()));
        let unit = render_unit("test", Some("/tmp"), &[], &options, Scope::User).unwrap();
        assert!(unit.contains("ExecStart=:\"/bin/sh\" \"-c\" \"printf '%%s' \\\"$HOME\\\"\" \"\" \"a b\" \"a\\\\b\""));
        assert!(unit.contains("Environment=\"TEST=hello $HOME 100%%\""));
        assert!(unit.contains("WorkingDirectory=/tmp\n"));
        assert!(unit.contains("KillMode=control-group\n"));
    }

    #[test]
    fn rejects_injection_and_unsupported_options() {
        let mut options = opts();
        options.command.push("x\nRestart=always".into());
        assert!(render_unit("test", None, &[], &options, Scope::User).is_err());
        let mut options = opts();
        options.env.push(("INVALID=KEY".into(), "x".into()));
        assert!(render_unit("test", None, &[], &options, Scope::User).is_err());
        let mut options = opts();
        options.restart_if.push(1);
        assert!(render_unit("test", None, &[], &options, Scope::User).is_err());
        let mut options = opts();
        options.stop_timeout = Some(0);
        assert!(render_unit("test", None, &[], &options, Scope::User).is_err());
    }

    #[test]
    fn restart_and_logging_policy() {
        let mut options = opts();
        assert!(
            render_unit("test", None, &[], &options, Scope::User)
                .unwrap()
                .contains("Restart=on-failure")
        );
        options.restart = true;
        options.restart_delay = Some(500);
        options.no_log = true;
        let unit = render_unit("test", None, &[], &options, Scope::User).unwrap();
        assert!(unit.contains("Restart=always"));
        assert!(unit.contains("RestartSec=500ms"));
        assert!(unit.contains("StandardOutput=null"));
    }
    #[test]
    fn system_scope_sets_non_root_account_and_boot_target() {
        let unit = render_unit("test", None, &[], &opts(), Scope::System("app-user")).unwrap();
        assert!(unit.contains("User=app-user\n"));
        assert!(unit.contains("WantedBy=multi-user.target\n"));
        let user = render_unit("test", None, &[], &opts(), Scope::User).unwrap();
        assert!(!user.contains("User="));
        assert!(user.contains("WantedBy=default.target\n"));
    }
    #[test]
    #[ignore = "requires the native systemd-analyze executable"]
    fn generated_native_config() {
        let dir = std::env::temp_dir().join(format!("shawl-systemd-verify-{}", std::process::id()));
        fs::create_dir(&dir).unwrap();
        let path = dir.join("shawl-test.service");
        let mut options = opts();
        options.env.push(("TEST".into(), "a $HOME 100%".into()));
        options.command.extend(["".into(), "a b".into(), "a\\b".into()]);
        let unit = render_unit("shawl-test", Some("/tmp"), &[], &options, Scope::User).unwrap();
        native::write_new(&path, &unit).unwrap();
        let output = Command::new("systemd-analyze")
            .env("XDG_RUNTIME_DIR", &dir)
            .args(["--user", "verify"])
            .arg(&path)
            .output();
        fs::remove_dir_all(&dir).unwrap();
        let output = output.expect("systemd-analyze must be available");
        assert!(
            output.status.success(),
            "systemd-analyze verify: {}",
            String::from_utf8_lossy(&output.stderr)
        );
    }
}
